export function getSourcesForCountry(countryCode: string): RadarSourceDefinition[] {
  const norm = countryCode.toUpperCase();
  if (norm === 'IN' || norm === 'INDIA') return MP_RADAR_SOURCES;
  if (norm === 'US' || norm === 'USA') return USA_RADAR_SOURCES;
  if (norm === 'GB' || norm === 'UK') return UK_RADAR_SOURCES;
  if (norm === 'DE' || norm === 'GERMANY') return GERMANY_RADAR_SOURCES;
  return ALL_GLOBAL_RADAR_SOURCES.filter((s) => s.country.toUpperCase() === norm);
}
